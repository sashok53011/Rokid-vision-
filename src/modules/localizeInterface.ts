const DICTIONARIES: Record<AppLanguage, TranslationDictionary> = {
  en: EN,
  ru: RU,
  de: DE,
};

export interface InterfaceTranslator {
  getLanguage(): AppLanguage;
  setLanguage(lang: AppLanguage): void;
  t(key: string): string;
  subscribe(listener: (lang: AppLanguage) => void): () => void;
}

/**
 * Создает переиспользуемый контроллер локализации интерфейса.
 *
 * @param initialLang Начальный язык ('en' | 'ru' | 'de').
 * @returns Объект с методами t(key), setLanguage(lang), getLanguage() и subscribe().
 */
export function createTranslator(initialLang: AppLanguage = 'en'): InterfaceTranslator {
  let currentLang: AppLanguage = initialLang;
  const listeners = new Set<(lang: AppLanguage) => void>();

  return {
    getLanguage: () => currentLang,
    setLanguage: (lang: AppLanguage) => {
      if (currentLang === lang) return;
      currentLang = lang;
      for (const listener of listeners) {
        listener(lang);
      }
    },
    t: (key: string) => {
      return DICTIONARIES[currentLang][key] ?? DICTIONARIES.en[key] ?? key;
    },
    subscribe: (listener: (lang: AppLanguage) => void) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
  };
}
